def get_gz(gz_str):
    tg = -1
    dz = -1
    for i, v in enumerate(TIAN_GAN):
        if gz_str[0] == v:
            tg = i
            break

    for i, v in enumerate(DI_ZHI):
        if gz_str[1] == v:
            dz = i
            break
    return sxtwl.GZ(tg, dz)


def get_jizhu(gan, zhi):

    gan_index = TIAN_GAN.index(gan)
    zhi_index = DI_ZHI.index(zhi)
    result = {}
    alls = []
    for i in range(6):
        ganzhi = f'{TIAN_GAN[(gan_index - 6 - i * 9) % 10]}{DI_ZHI[(zhi_index - 6 - i * 9) % 12]}'
        result[ganzhi] = get_year_of_ganzhi(ganzhi)
        alls += result[ganzhi]
    alls.sort()
    result['all'] = alls
    return result


def get_year_of_ganzhi(ganzhi):

    seq = HUA_JIA_60.inverse[ganzhi]
    year = 1983 + seq
    current_year = get_current_year()
    result = [year - 60]
    if year <= current_year:
        result.append(year)
    return result


